"""Requirement traceability matrix (SOTA ARCH-1).

Collects requirement ids from:
  - pytest: @pytest.mark.req("ID", ...) on test functions (tests/*.py)
  - node:test: test names that start with "ID:" or "ID/ID2:" (frontend/tests/*.test.js)
  - end-to-end: check("ID ...") lines in ci/e2e_chat.js

and writes docs/assurance/traceability.md. `--check` fails if the committed
file is stale, so the matrix can never drift from the tests.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "assurance" / "traceability.md"
ID = r"[A-Z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)*"


def _mark_ids(dec: ast.expr) -> list[str]:
    # pytest.mark.req("A", "B")
    if (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute) and dec.func.attr == "req"
            and isinstance(dec.func.value, ast.Attribute) and dec.func.value.attr == "mark"):
        return [a.value for a in dec.args if isinstance(a, ast.Constant) and isinstance(a.value, str)]
    return []


def python_tests() -> dict[str, set[str]]:
    found: dict[str, set[str]] = defaultdict(set)
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                for dec in node.decorator_list:
                    for rid in _mark_ids(dec):
                        found[rid].add(f"`tests/{path.name}::{node.name}`")
    return found


def js_tests() -> dict[str, set[str]]:
    found: dict[str, set[str]] = defaultdict(set)
    for path in sorted((ROOT / "frontend" / "tests").glob("*.test.js")):
        for m in re.finditer(r'test\("((?:' + ID + r')(?:/' + ID + r')*):\s*([^"]+)"', path.read_text()):
            for rid in m.group(1).split("/"):
                found[rid].add(f"`frontend/tests/{path.name}` — {m.group(2)}")
    e2e = ROOT / "ci" / "e2e_chat.js"
    for m in re.finditer(r'check\("((?:' + ID + r')(?:/' + ID + r')*) ([^"]+)"', e2e.read_text()):
        for rid in m.group(1).split("/"):
            found[rid].add(f"`ci/e2e_chat.js` — {m.group(2)}")
    return found


def render() -> str:
    merged: dict[str, set[str]] = defaultdict(set)
    for src in (python_tests(), js_tests()):
        for rid, tests in src.items():
            merged[rid] |= tests
    lines = [
        "# Requirement traceability matrix",
        "",
        "Generated by `python3 ci/trace_matrix.py` from requirement ids on the tests themselves",
        "(`@pytest.mark.req`, node test names, e2e check names). CI runs it with `--check`,",
        "so this file cannot drift from the tests. Do not edit by hand.",
        "",
        "Ids are SOTA v1.0 clauses (DES/MOT/INT/ARCH/SEC/VER/OPS), NPR 7150.2D SWE items mapped",
        "by analogy (not a compliance claim), and product requirements of this repo.",
        "",
        f"Requirements covered: {len(merged)} · test references: {sum(len(v) for v in merged.values())}",
        "",
        "| Requirement | Tests |",
        "|---|---|",
    ]
    for rid in sorted(merged):
        lines.append(f"| {rid} | " + "<br>".join(sorted(merged[rid])) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the committed matrix is stale")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("traceability matrix is stale: run python3 ci/trace_matrix.py and commit", file=sys.stderr)
            return 1
        print("traceability matrix: up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
